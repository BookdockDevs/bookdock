import { act, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'

import { LibrarySearchError } from '@bookdock/shared'

import LibrarySearchInput from './LibrarySearchInput'

vi.mock('@/hooks/useTranslation', () => ({
  useTranslation: () => (key: string) => ({
    'library.searchNotApplied': '未应用',
    'library.searchLocateError': '修改',
    'library.searchSubmit': '搜索',
    'library.searchClear': '退出搜索',
  } as Record<string, string>)[key] ?? key,
}))

afterEach(() => vi.useRealTimers())

describe('library search draft interaction', () => {
  it('cycles suggestions without moving focus or applying and accepts before Enter submits', async () => {
    vi.useFakeTimers()
    const onSubmit = vi.fn().mockResolvedValue(undefined)
    render(<LibrarySearchInput query="" placeholder="搜索" names={{ shared: false, tags: [{ id: 'a', name: '太空 科幻' }, { id: 'b', name: '太空 奇幻' }], categories: [] }} onSubmit={onSubmit} />)
    const input = screen.getByRole('combobox') as HTMLInputElement
    input.focus()
    fireEvent.change(input, { target: { value: 'tag:太空' } })
    const options = screen.getAllByRole('option')
    expect(input.getAttribute('aria-activedescendant')).toBeNull()
    fireEvent.keyDown(input, { key: 'ArrowDown' })
    expect(options[0].getAttribute('aria-selected')).toBe('true')
    expect(input.getAttribute('aria-activedescendant')).toBe(options[0].id)
    expect(document.activeElement).toBe(input)
    expect(input.value).toBe('tag:太空')
    await act(() => vi.advanceTimersByTimeAsync(1000))
    expect(onSubmit).not.toHaveBeenCalled()
    fireEvent.keyDown(input, { key: 'ArrowUp' })
    expect(options[1].getAttribute('aria-selected')).toBe('true')
    fireEvent.keyDown(input, { key: 'ArrowDown' })
    expect(options[0].getAttribute('aria-selected')).toBe('true')
    fireEvent.keyDown(input, { key: 'ArrowDown' })
    fireEvent.keyDown(input, { key: 'Enter' })
    expect(input.value).toBe('tag:"太空 奇幻"')
    expect(screen.queryByRole('listbox')).toBeNull()
    expect(onSubmit).not.toHaveBeenCalled()
    await act(async () => { fireEvent.keyDown(input, { key: 'Enter' }) })
    expect(onSubmit).toHaveBeenCalledWith('tag:"太空 奇幻"', expect.any(AbortSignal))
  })
  it('accepts the first suggestion with Tab, preserves suffix and caret, then resumes live search', async () => {
    vi.useFakeTimers()
    const onSubmit = vi.fn().mockResolvedValue(undefined)
    render(<LibrarySearchInput query="" placeholder="搜索" onSubmit={onSubmit} />)
    const input = screen.getByRole('combobox') as HTMLInputElement
    fireEvent.focus(input)
    fireEvent.change(input, { target: { value: 'format:ep & 三体', selectionStart: 9 } })
    const tab = new KeyboardEvent('keydown', { key: 'Tab', bubbles: true, cancelable: true })
    fireEvent(input, tab)
    expect(tab.defaultPrevented).toBe(true)
    expect(input.value).toBe('format:"epub" & 三体')
    expect(input.selectionStart).toBe(13)
    expect(input.selectionEnd).toBe(13)
    await act(() => vi.advanceTimersByTimeAsync(300))
    expect(onSubmit).toHaveBeenCalledWith('format:"epub" & 三体', expect.any(AbortSignal))
    const nextTab = new KeyboardEvent('keydown', { key: 'Tab', bubbles: true, cancelable: true })
    fireEvent(input, nextTab)
    expect(nextTab.defaultPrevented).toBe(false)
  })
  it('shares mouse highlighting, resets on edit and dismisses without changing the draft', () => {
    render(<LibrarySearchInput query="" placeholder="搜索" onSubmit={vi.fn()} />)
    const input = screen.getByRole('combobox') as HTMLInputElement
    fireEvent.focus(input)
    fireEvent.change(input, { target: { value: 'format:e' } })
    const option = screen.getByRole('option', { name: 'epub' })
    fireEvent.mouseMove(option)
    expect(option.getAttribute('aria-selected')).toBe('true')
    fireEvent.change(input, { target: { value: 'format:ep' } })
    expect(input.getAttribute('aria-activedescendant')).toBeNull()
    fireEvent.keyDown(input, { key: 'ArrowUp' })
    fireEvent.keyDown(input, { key: 'Escape' })
    expect(input.value).toBe('format:ep')
    expect(input.getAttribute('aria-expanded')).toBe('false')
    expect(input.getAttribute('aria-activedescendant')).toBeNull()
    fireEvent.change(input, { target: { value: 'format:e' } })
    expect(screen.getByRole('option').getAttribute('aria-selected')).toBe('false')
    const shiftTab = new KeyboardEvent('keydown', { key: 'Tab', shiftKey: true, bubbles: true, cancelable: true })
    fireEvent(input, shiftTab)
    expect(shiftTab.defaultPrevented).toBe(false)
  })
  it('does not intercept suggestion keys during IME composition', () => {
    const onSubmit = vi.fn()
    render(<LibrarySearchInput query="" placeholder="搜索" onSubmit={onSubmit} />)
    const input = screen.getByRole('combobox') as HTMLInputElement
    fireEvent.focus(input)
    fireEvent.change(input, { target: { value: 'format:ep' } })
    for (const key of ['ArrowDown', 'ArrowUp', 'Tab', 'Enter', 'Escape']) {
      const event = new KeyboardEvent('keydown', { key, isComposing: true, bubbles: true, cancelable: true })
      fireEvent(input, event)
      expect(event.defaultPrevented).toBe(false)
    }
    expect(input.value).toBe('format:ep')
    expect(input.getAttribute('aria-activedescendant')).toBeNull()
    expect(onSubmit).not.toHaveBeenCalled()
    fireEvent.compositionStart(input)
    expect(screen.queryByRole('listbox')).toBeNull()
    fireEvent.keyDown(input, { key: 'Enter' })
    expect(onSubmit).not.toHaveBeenCalled()
  })
  it('does not apply typing and retains failed drafts and the applied query', async () => {
    const onSubmit = vi.fn().mockRejectedValue(new LibrarySearchError('标签不存在', 4, 6))
    const { rerender } = render(<LibrarySearchInput query="old result" placeholder="搜索" onSubmit={onSubmit} />)
    const input = screen.getByRole('combobox') as HTMLInputElement
    fireEvent.change(input, { target: { value: 'tag:坏值' } })
    expect(onSubmit).not.toHaveBeenCalled()
    fireEvent.keyDown(input, { key: 'Enter' })
    await screen.findByRole('alert')
    expect(input.value).toBe('tag:坏值')
    expect(screen.getByRole('alert').textContent).toContain('未应用')
    fireEvent.click(screen.getByRole('button', { name: '修改' }))
    expect(input.selectionStart).toBe(4)
    expect(input.selectionEnd).toBe(6)
    rerender(<LibrarySearchInput query="restored URL" placeholder="搜索" onSubmit={onSubmit} />)
    expect(input.value).toBe('restored URL')
    expect(screen.queryByRole('alert')).toBeNull()
  })
  it('submits the same draft from the visible button and blocks duplicate submission', async () => {
    let finish!: () => void
    const onSubmit = vi.fn(() => new Promise<void>((resolve) => { finish = resolve }))
    render(<LibrarySearchInput query="" placeholder="搜索" onSubmit={onSubmit} />)
    const input = screen.getByRole('combobox')
    const button = screen.getByRole('button', { name: '搜索' }) as HTMLButtonElement
    fireEvent.change(input, { target: { value: '三体' } })
    fireEvent.click(button)
    expect(onSubmit).toHaveBeenCalledWith('三体', expect.any(AbortSignal))
    expect(button.disabled).toBe(true)
    fireEvent.click(button)
    fireEvent.keyDown(input, { key: 'Enter' })
    expect(onSubmit).toHaveBeenCalledTimes(1)
    finish()
    await waitFor(() => expect(button.disabled).toBe(false))
  })
  it('ignores IME Enter and offers quoted name completion without submitting', () => {
    const onSubmit = vi.fn()
    render(<LibrarySearchInput query="" placeholder="搜索" names={{ shared: false, tags: [{ id: 'a', name: '太空 科幻' }], categories: [] }} onSubmit={onSubmit} />)
    const input = screen.getByRole('combobox') as HTMLInputElement
    fireEvent.focus(input)
    fireEvent.change(input, { target: { value: 'tag:太空' } })
    fireEvent.keyDown(input, { key: 'Enter', isComposing: true })
    expect(onSubmit).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('option', { name: '太空 科幻' }))
    expect(input.value).toBe('tag:"太空 科幻"')
    expect(screen.queryByRole('option', { name: '太空 科幻' })).toBeNull()
    expect(onSubmit).not.toHaveBeenCalled()
  })
  it('only suggests unfinished values and dismisses suggestions until editing resumes', async () => {
    const onSubmit = vi.fn().mockResolvedValue(undefined)
    render(<LibrarySearchInput query="format:ep" placeholder="搜索" onSubmit={onSubmit} />)
    const input = screen.getByRole('combobox')
    fireEvent.focus(input)
    expect(screen.queryByRole('option', { name: 'epub' })).toBeNull()
    fireEvent.change(input, { target: { value: 'format:epu' } })
    expect(screen.getByRole('option', { name: 'epub' })).toBeTruthy()
    fireEvent.keyDown(input, { key: 'Escape' })
    expect(screen.queryByRole('option', { name: 'epub' })).toBeNull()
    fireEvent.change(input, { target: { value: 'format:ep' } })
    expect(screen.getByRole('option', { name: 'epub' })).toBeTruthy()
    fireEvent.keyDown(input, { key: 'Enter' })
    expect(screen.queryByRole('option', { name: 'epub' })).toBeNull()
    await waitFor(() => expect(screen.queryByRole('status')).toBeNull())
    expect(screen.queryByRole('option', { name: 'epub' })).toBeNull()
    fireEvent.change(input, { target: { value: 'format:epub' } })
    expect(screen.queryByRole('option', { name: 'epub' })).toBeNull()
    fireEvent.change(input, { target: { value: 'format:ep' } })
    fireEvent.click(screen.getByRole('option', { name: 'epub' }))
    expect(screen.queryByRole('option', { name: 'epub' })).toBeNull()
  })
  it('aborts validation when the draft changes or the component leaves its library', async () => {
    const signals: AbortSignal[] = []
    const onSubmit = vi.fn((_source, signal: AbortSignal) => { signals.push(signal); return new Promise(() => {}) })
    const { unmount } = render(<LibrarySearchInput query="" placeholder="搜索" onSubmit={onSubmit} />)
    const input = screen.getByRole('combobox')
    fireEvent.change(input, { target: { value: 'first' } }); fireEvent.keyDown(input, { key: 'Enter' })
    fireEvent.change(input, { target: { value: 'second' } })
    expect(signals[0].aborted).toBe(true)
    fireEvent.keyDown(input, { key: 'Enter' })
    await waitFor(() => expect(signals).toHaveLength(2))
    unmount()
    expect(signals[1].aborted).toBe(true)
  })
  it('automatically applies both keywords and complete expressions after 300 ms', async () => {
    vi.useFakeTimers()
    const onSubmit = vi.fn().mockResolvedValue(undefined)
    render(<LibrarySearchInput query="" placeholder="搜索" onSubmit={onSubmit} />)
    const input = screen.getByRole('combobox')
    fireEvent.change(input, { target: { value: '三' } })
    await act(() => vi.advanceTimersByTimeAsync(200))
    fireEvent.change(input, { target: { value: '三体' } })
    await act(() => vi.advanceTimersByTimeAsync(299))
    expect(onSubmit).not.toHaveBeenCalled()
    await act(() => vi.advanceTimersByTimeAsync(1))
    expect(onSubmit).toHaveBeenCalledWith('三体', expect.any(AbortSignal))
    fireEvent.change(input, { target: { value: '三体 format:txt' } })
    await act(() => vi.advanceTimersByTimeAsync(300))
    expect(onSubmit).toHaveBeenLastCalledWith('三体 format:txt', expect.any(AbortSignal))
    expect(onSubmit).toHaveBeenCalledTimes(2)
    expect(screen.queryByRole('status')).toBeNull()
  })
  it('waits for IME completion and keeps unfinished syntax quiet until explicit submission', async () => {
    vi.useFakeTimers()
    const onSubmit = vi.fn().mockResolvedValue(undefined)
    render(<LibrarySearchInput query="" placeholder="搜索" onSubmit={onSubmit} />)
    const input = screen.getByRole('combobox')
    fireEvent.compositionStart(input)
    fireEvent.change(input, { target: { value: '三体' } })
    await act(() => vi.advanceTimersByTimeAsync(600))
    expect(onSubmit).not.toHaveBeenCalled()
    fireEvent.compositionEnd(input)
    await act(() => vi.advanceTimersByTimeAsync(300))
    expect(onSubmit).toHaveBeenCalledTimes(1)
    fireEvent.change(input, { target: { value: 'tag:科幻 |' } })
    await act(() => vi.advanceTimersByTimeAsync(600))
    expect(screen.queryByRole('alert')).toBeNull()
    expect(onSubmit).toHaveBeenCalledTimes(1)
    await act(async () => { fireEvent.keyDown(input, { key: 'Enter' }) })
    expect(screen.getByRole('alert').textContent).toContain('运算符缺少操作数')
  })
  it('clears a pending draft immediately and cancels automatic work', async () => {
    vi.useFakeTimers()
    const onClear = vi.fn()
    const onSubmit = vi.fn(() => new Promise(() => {}))
    render(<LibrarySearchInput query="" placeholder="搜索" onSubmit={onSubmit} onClear={onClear} />)
    const input = screen.getByRole('combobox') as HTMLInputElement
    fireEvent.change(input, { target: { value: 'word' } })
    await act(() => vi.advanceTimersByTimeAsync(300))
    const signal = onSubmit.mock.calls[0][1] as AbortSignal
    fireEvent.click(screen.getByRole('button', { name: '退出搜索' }))
    expect(input.value).toBe('')
    expect(signal.aborted).toBe(true)
    expect(onClear).toHaveBeenCalledTimes(1)
    await act(() => vi.advanceTimersByTimeAsync(1000))
    expect(onSubmit).toHaveBeenCalledTimes(1)
    expect(screen.queryByRole('status')).toBeNull()
  })
  it('does not rewrite the typed expression when its own result updates URL state', async () => {
    const onSubmit = vi.fn(() => new Promise(() => {}))
    const { rerender } = render(<LibrarySearchInput query="" placeholder="搜索" onSubmit={onSubmit} />)
    const input = screen.getByRole('combobox') as HTMLInputElement
    fireEvent.change(input, { target: { value: 'word format:txt' } })
    fireEvent.keyDown(input, { key: 'Enter' })
    rerender(<LibrarySearchInput query="word & format:txt" placeholder="搜索" onSubmit={onSubmit} />)
    expect(input.value).toBe('word format:txt')
    rerender(<LibrarySearchInput query="restored previous search" placeholder="搜索" onSubmit={onSubmit} />)
    expect(input.value).toBe('restored previous search')
  })
  it('keeps automatic name errors quiet but exposes request failures', async () => {
    vi.useFakeTimers()
    const onSubmit = vi.fn().mockRejectedValue(new LibrarySearchError('标签不存在', 0, 8))
    render(<LibrarySearchInput query="" placeholder="搜索" onSubmit={onSubmit} />)
    const input = screen.getByRole('combobox')
    fireEvent.change(input, { target: { value: 'tag:missing' } })
    await act(() => vi.advanceTimersByTimeAsync(300))
    expect(screen.queryByRole('alert')).toBeNull()
    await act(async () => { fireEvent.keyDown(input, { key: 'Enter' }) })
    expect(screen.getByRole('alert').textContent).toContain('标签不存在')
    onSubmit.mockRejectedValue(new Error('Network unavailable'))
    fireEvent.change(input, { target: { value: 'word' } })
    await act(() => vi.advanceTimersByTimeAsync(300))
    expect(screen.getByRole('alert').textContent).toContain('Network unavailable')
  })
})
